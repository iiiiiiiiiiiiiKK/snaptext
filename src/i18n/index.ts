export const dictionaries = { en, zh } as const;

export type UiLang = keyof typeof dictionaries;

export type Translate = (key: I18nKey, vars?: Record<string, string | number>) => string;

export function createTranslator(lang: UiLang): Translate {
  const table = dictionaries[lang];
  return (key, vars) => {
    const template = table[key] ?? en[key] ?? key;
    if (!vars) return template;
    return Object.entries(vars).reduce(
      (acc, [name, value]) => acc.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
      template,
    );
  };
}

export function detectUiLang(locale: string): UiLang {
  return locale.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function isI18nKey(key: string): key is I18nKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

/** Translate an error code (`errors.<code>`), falling back to the raw code. */
export function translateError(
  t: Translate,
  code: string,
  vars?: Record<string, string | number>,
): string {
  const key = `errors.${code}`;
  return isI18nKey(key) ? t(key, vars) : code;
}

